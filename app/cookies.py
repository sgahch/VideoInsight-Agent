from __future__ import annotations

import json
from pathlib import Path
from time import time


DEFAULT_COOKIE_DOMAIN = ".douyin.com"
IMPORTANT_DOUYIN_COOKIES = {
    "sessionid",
    "sid_guard",
    "sid_tt",
    "passport_csrf_token",
    "odin_tt",
    "ttwid",
    "msToken",
    "s_v_web_id",
}
LOGIN_COOKIE_NAMES = {"sessionid", "sid_guard", "sid_tt"}


def normalize_cookie_upload(raw: bytes, domain: str = DEFAULT_COOKIE_DOMAIN) -> str:
    text = raw.decode("utf-8", errors="replace").strip()
    if not text:
        return "# Netscape HTTP Cookie File\n"
    if _looks_like_cookie_json(text):
        return cookie_json_to_netscape(text, domain)
    if _looks_like_netscape(text):
        return text if text.endswith("\n") else text + "\n"
    return header_cookie_to_netscape(text, domain)


def header_cookie_to_netscape(cookie_text: str, domain: str = DEFAULT_COOKIE_DOMAIN) -> str:
    cookie_text = cookie_text.strip()
    if cookie_text.lower().startswith("cookie:"):
        cookie_text = cookie_text.split(":", 1)[1].strip()

    expires = int(time()) + 180 * 24 * 60 * 60
    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by VideoInsight Agent from a Cookie header.",
    ]
    for item in cookie_text.split(";"):
        item = item.strip()
        if not item or "=" not in item:
            continue
        name, value = item.split("=", 1)
        name = name.strip()
        if not name:
            continue
        lines.append(f"{domain}\tTRUE\t/\tFALSE\t{expires}\t{name}\t{value.strip()}")
    return "\n".join(lines) + "\n"


def cookie_json_to_netscape(cookie_text: str, domain: str = DEFAULT_COOKIE_DOMAIN) -> str:
    payload = json.loads(cookie_text)
    cookies = payload.get("cookies") if isinstance(payload, dict) else payload

    if isinstance(cookies, dict):
        cookies = [{"name": name, "value": value, "domain": domain} for name, value in cookies.items()]
    if not isinstance(cookies, list):
        raise ValueError("Cookie JSON must be a list, a name/value object, or an object with a cookies list.")

    return cookie_objects_to_netscape(cookies, source="Cookie Editor JSON", fallback_domain=domain)


def cookie_dict_to_netscape(cookies: dict[str, str], domain: str = DEFAULT_COOKIE_DOMAIN) -> str:
    cookie_objects = [{"name": name, "value": value, "domain": domain} for name, value in cookies.items()]
    return cookie_objects_to_netscape(cookie_objects, source="QR login session", fallback_domain=domain)


def cookie_objects_to_netscape(
    cookies: list[dict],
    source: str,
    fallback_domain: str = DEFAULT_COOKIE_DOMAIN,
) -> str:
    expires_default = int(time()) + 180 * 24 * 60 * 60
    lines = [
        "# Netscape HTTP Cookie File",
        f"# Generated by VideoInsight Agent from {source}.",
    ]
    for cookie in cookies:
        name = str(cookie.get("name") or "").strip()
        value = str(cookie.get("value") or "")
        if not name:
            continue

        cookie_domain = str(cookie.get("domain") or fallback_domain).strip() or fallback_domain
        if "douyin.com" not in cookie_domain and "bytedance.com" not in cookie_domain:
            continue
        if not cookie_domain.startswith(".") and cookie_domain.endswith("douyin.com"):
            cookie_domain = "." + cookie_domain.removeprefix("www.")

        path = str(cookie.get("path") or "/")
        secure = "TRUE" if cookie.get("secure") else "FALSE"
        expires = _cookie_expires(cookie, expires_default)
        include_subdomains = "TRUE" if cookie_domain.startswith(".") else "FALSE"
        lines.append(f"{cookie_domain}\t{include_subdomains}\t{path}\t{secure}\t{expires}\t{name}\t{value}")
    return "\n".join(lines) + "\n"


def summarize_cookie_text(text: str) -> dict[str, object]:
    rows = [
        line.split("\t")
        for line in text.splitlines()
        if line.strip() and not line.startswith("#") and "\t" in line
    ]
    names = {row[5] for row in rows if len(row) >= 7}
    present = sorted(name for name in IMPORTANT_DOUYIN_COOKIES if name in names)
    missing = sorted(name for name in IMPORTANT_DOUYIN_COOKIES if name not in names)
    return {
        "count": len([row for row in rows if len(row) >= 7]),
        "has_login_cookie": bool(names & LOGIN_COOKIE_NAMES),
        "present_important": present,
        "missing_important": missing,
    }


def summarize_cookie_file(path: Path) -> dict[str, object]:
    if not path.exists():
        return {
            "exists": False,
            "count": 0,
            "has_login_cookie": False,
            "present_important": [],
            "missing_important": sorted(IMPORTANT_DOUYIN_COOKIES),
        }
    summary = summarize_cookie_text(path.read_text(encoding="utf-8", errors="replace"))
    return {
        "exists": True,
        "path": str(path),
        "size": path.stat().st_size,
        **summary,
    }


def _looks_like_netscape(text: str) -> bool:
    lines = [line for line in text.splitlines() if line.strip() and not line.startswith("#")]
    return any("\t" in line and len(line.split("\t")) >= 7 for line in lines)


def _looks_like_cookie_json(text: str) -> bool:
    return text.startswith("[") or text.startswith("{")


def _cookie_expires(cookie: dict, default: int) -> int:
    value = cookie.get("expires")
    if value in (None, "", -1):
        value = cookie.get("expirationDate")
    try:
        expires = int(float(value))
    except (TypeError, ValueError):
        expires = default
    return expires if expires > 0 else default


def write_normalized_cookie_file(target: Path, raw: bytes, domain: str = DEFAULT_COOKIE_DOMAIN) -> Path:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(normalize_cookie_upload(raw, domain), encoding="utf-8")
    return target
